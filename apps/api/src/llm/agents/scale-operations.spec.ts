/**
 * Operational proportionality, across every stage that recommends tooling.
 *
 * `scale-scenarios.spec.ts` proved the *architecture* is sized to the client's
 * numbers. It did not — and could not — see the second half of the bug: the
 * roadmap, QA plan, threat model and review each recommend infrastructure and
 * tooling of their own, none of them had ever been told a tier existed, and so
 * each one fell back on the prior the architect had just been cured of. The
 * reported symptom was a Hardening phase scheduling Prometheus and an ELK stack
 * for a five-figure MVP whose design had one process and one managed database.
 *
 * The two scenarios are imported, not re-declared, so "every stage agrees about
 * this project" is a claim about ONE project rather than two that happen to
 * match.
 *
 * Both directions are asserted. A change that only ever strips advanced tooling
 * passes half this file and is a different bug — an enterprise platform with no
 * centralized logging is an outage nobody can diagnose.
 */

import type {
  ApiDesign,
  DatabaseDesign,
  RequirementDocument,
  SystemDesign,
} from '@archivato/shared';
import { SystemArchitectAgent } from './system-architect.agent';
import { DatabaseDesignerAgent } from './database-designer.agent';
import { ApiDesignerAgent } from './api-designer.agent';
import { RoadmapPlannerAgent } from './roadmap-planner.agent';
import { QaPlannerAgent } from './qa-planner.agent';
import { ThreatModelerAgent } from './threat-modeler.agent';
import { ReviewerAgent } from './reviewer.agent';
import { MockLlmProvider } from '../mock-llm.provider';
import type { LlmProvider } from '../llm-provider.interface';
import {
  CLINIC_IDEA,
  clinicRequirements,
  clinicSlots,
  TASK_BOARD_IDEA,
  taskBoardRequirements,
  taskBoardSlots,
} from './scale-scenarios.fixtures';

jest.setTimeout(30_000);

/** Every artifact a downstream stage reads, generated by the real agents. */
interface Pipeline {
  requirements: RequirementDocument;
  systemDesign: SystemDesign;
  databaseDesign: DatabaseDesign;
  apiDesign: ApiDesign;
}

async function buildPipeline(
  id: string,
  idea: string,
  requirements: RequirementDocument,
  slots: ReturnType<typeof taskBoardSlots>,
): Promise<Pipeline> {
  const llm = new MockLlmProvider();
  const systemDesign = await new SystemArchitectAgent(llm).generate(id, {
    idea,
    intent: null,
    requirements,
    slots,
  });
  const databaseDesign = await new DatabaseDesignerAgent(llm).generate(id, {
    idea,
    intent: null,
    requirements,
    systemDesign,
  });
  const apiDesign = await new ApiDesignerAgent(llm).generate(id, {
    idea,
    intent: null,
    requirements,
    systemDesign,
    databaseDesign,
  });
  return { requirements, systemDesign, databaseDesign, apiDesign };
}

const downstreamCtx = (idea: string, p: Pipeline) => ({ idea, intent: null, ...p });

/** Every string a stage's artifact puts in front of the owner, lowercased. */
const roadmapText = (r: Awaited<ReturnType<RoadmapPlannerAgent['generate']>>) =>
  r.phases
    .flatMap((p) => [
      p.name,
      p.goal,
      ...p.milestones.flatMap((m) => [
        m.title,
        ...m.tasks.flatMap((t) => [t.title, t.detail ?? '']),
      ]),
    ])
    .join(' ')
    .toLowerCase();

/** Records every prompt sent, then returns nothing so the fallback path runs. */
function recordingLlm(): { llm: LlmProvider; prompts: () => string } {
  const seen: string[] = [];
  const llm = {
    name: 'recording',
    complete: async () => '{}',
    completeJson: async (messages: unknown) => {
      seen.push(JSON.stringify(messages));
      return {} as never;
    },
  } as unknown as LlmProvider;
  return { llm, prompts: () => seen.join('\n') };
}

// ── scenario A: the reported small MVP ──────────────────────────────────────

describe('small tier: the reported lightweight task board', () => {
  let pipeline: Pipeline;

  beforeAll(async () => {
    pipeline = await buildPipeline(
      's1',
      TASK_BOARD_IDEA,
      taskBoardRequirements(),
      taskBoardSlots(),
    );
    // Guards every assertion below: if the architect ever stopped reading this
    // project as small, the rest of the file would pass for the wrong reason.
    expect(pipeline.systemDesign.scaleTier).toBe('small');
  });

  it('plans observability the team can actually run, not a monitoring platform', async () => {
    const roadmap = await new RoadmapPlannerAgent(new MockLlmProvider()).generate(
      's1',
      downstreamCtx(TASK_BOARD_IDEA, pipeline),
    );
    const text = roadmapText(roadmap);

    // The reported output, gone.
    expect(text).not.toContain('prometheus');
    expect(text).not.toContain('elk');
    expect(text).not.toContain('grafana');
    expect(text).not.toContain('datadog');
    // …and replaced by something, not merely deleted. A plan with no
    // observability at all is a different wrong answer.
    expect(text).toMatch(/health|log/);
  });

  it('does not schedule work on infrastructure the design does not have', async () => {
    // The offline path had the bug more sharply than the model did: it scheduled
    // "Add caching for read-heavy endpoints" on a design the tier had just
    // stripped the cache from — the plan contradicting the architecture inside
    // one package.
    const roadmap = await new RoadmapPlannerAgent(new MockLlmProvider()).generate(
      's1',
      downstreamCtx(TASK_BOARD_IDEA, pipeline),
    );
    const stack = pipeline.systemDesign.techStack
      .map((t) => `${t.layer} ${t.technology}`)
      .join(' ')
      .toLowerCase();

    expect(stack).not.toContain('redis');
    expect(roadmapText(roadmap)).not.toContain('caching');
  });

  it('recommends QA tooling proportional to the tier', async () => {
    const plan = await new QaPlannerAgent(new MockLlmProvider()).generate(
      's1',
      downstreamCtx(TASK_BOARD_IDEA, pipeline),
    );
    const tooling = plan.tooling.join(' ').toLowerCase();

    expect(tooling).not.toContain('testcontainers');
    // The testing base itself is never cut — that would be cutting testing, not
    // cutting scale.
    expect(tooling).toMatch(/jest|test runner/);
    expect(tooling).toMatch(/playwright|cypress/);
  });

  it('mitigates threats with controls this team can operate', async () => {
    const model = await new ThreatModelerAgent(new MockLlmProvider()).generate(
      's1',
      downstreamCtx(TASK_BOARD_IDEA, pipeline),
    );
    const mitigations = model.threats.map((t) => t.mitigation.toLowerCase());

    // A WAF is a product to buy and tune; recommending one here produces a
    // mitigation nobody implements, which reads as done and leaves the threat open.
    expect(mitigations.some((m) => m.includes('waf'))).toBe(false);
    // The threat is still raised — severity never scales down with the budget.
    expect(model.threats.some((t) => t.category === 'denial_of_service')).toBe(true);
    // And the security controls that ARE free still appear.
    expect(mitigations.join(' ')).toContain('rate limit');
  });

  it('does not tell a queue-less design it is missing a queue', async () => {
    const model = await new ThreatModelerAgent(new MockLlmProvider()).generate(
      's1',
      downstreamCtx(TASK_BOARD_IDEA, pipeline),
    );
    const dos = model.threats
      .filter((t) => t.category === 'denial_of_service')
      .map((t) => t.mitigation.toLowerCase())
      .join(' ');

    expect(dos).not.toContain('background queue');
  });

  it('does not review a correctly-sized design as under-built', async () => {
    // The worst of the four: the review adjudicates the other artifacts, and it
    // was marking the design down on two axes for the simplicity the architect
    // was instructed to choose — then offering a `patch` that would write Redis
    // straight back into the tech stack.
    const review = await new ReviewerAgent(new MockLlmProvider()).generate(
      's1',
      downstreamCtx(TASK_BOARD_IDEA, pipeline),
    );
    const titles = [
      ...review.scalabilityIssues,
      ...review.performanceRisks,
      ...review.costOptimizations,
    ].map((f) => f.title.toLowerCase());

    expect(titles).not.toContain('no caching layer');
    expect(titles).not.toContain('no asynchronous processing');
    expect(titles).not.toContain('add a caching layer');
    expect(review.recommendations.join(' ').toLowerCase()).not.toContain(
      'caching layer',
    );
  });

  it('does not depress the scalability score for right-sized simplicity', async () => {
    const review = await new ReviewerAgent(new MockLlmProvider()).generate(
      's1',
      downstreamCtx(TASK_BOARD_IDEA, pipeline),
    );
    // The absent queue and cache were worth 18 points between them, so a
    // correctly-sized design used to score mid-60s for doing the right thing.
    expect(review.scores.scalability).toBeGreaterThanOrEqual(80);
  });
});

