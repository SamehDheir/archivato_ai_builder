// ── the backstop, on the path that actually shipped the bug ─────────────────

describe('the roadmap backstop (LLM path, small tier)', () => {
  async function smallPipeline(): Promise<Pipeline> {
    return buildPipeline('s1', TASK_BOARD_IDEA, taskBoardRequirements(), taskBoardSlots());
  }

  /** The exact milestone the user reported, verbatim. */
  const reportedPhase = {
    name: 'Hardening & Launch',
    goal: 'Production readiness.',
    dependsOn: [],
    moduleNames: [],
    milestones: [
      {
        title: 'Monitoring & Logging',
        tasks: [
          { title: 'Integrate Prometheus metrics', detail: 'Expose /metrics endpoint' },
          { title: 'Centralized logging', detail: 'Send logs to ELK stack' },
        ],
      },
    ],
  };

  it('replaces an emptied observability milestone rather than deleting it', async () => {
    const pipeline = await smallPipeline();
    const mock = new MockLlmProvider();
    mock.enqueueJson({ summary: 'plan', phases: [reportedPhase] });

    const roadmap = await new RoadmapPlannerAgent(mock).generate(
      's1',
      downstreamCtx(TASK_BOARD_IDEA, pipeline),
    );
    const milestone = roadmap.phases[0].milestones[0];

    expect(milestone.title).toBe('Monitoring & Logging');
    // Deleting both tasks would have left a plan with no observability at all.
    expect(milestone.tasks).toHaveLength(1);
    expect(milestone.tasks[0].title.toLowerCase()).toMatch(/log|health/);
    expect(roadmapText(roadmap)).not.toContain('prometheus');
  });

  it('leaves a milestone alone when proportional tasks survive alongside', async () => {
    const pipeline = await smallPipeline();
    const mock = new MockLlmProvider();
    mock.enqueueJson({
      summary: 'plan',
      phases: [
        {
          ...reportedPhase,
          milestones: [
            {
              title: 'Monitoring & Logging',
              tasks: [
                { title: 'Add a /health endpoint' },
                { title: 'Ship logs to a Grafana Loki cluster' },
              ],
            },
          ],
        },
      ],
    });

    const roadmap = await new RoadmapPlannerAgent(mock).generate(
      's1',
      downstreamCtx(TASK_BOARD_IDEA, pipeline),
    );
    const tasks = roadmap.phases[0].milestones[0].tasks.map((t) => t.title);

    expect(tasks).toEqual(['Add a /health endpoint']);
  });

  it('does not strip a search task that merely names a search engine', async () => {
    // The backstop walks EVERY phase, not just Hardening. A Supporting Features
    // task indexing products for search is not an operations recommendation, and
    // an over-broad pattern would silently delete real scope.
    const pipeline = await smallPipeline();
    const mock = new MockLlmProvider();
    mock.enqueueJson({
      summary: 'plan',
      phases: [
        {
          name: 'Supporting features',
          goal: 'Search.',
          dependsOn: [],
          moduleNames: [],
          milestones: [
            {
              title: 'Search',
              tasks: [{ title: 'Index tasks in Elasticsearch for full-text search' }],
            },
          ],
        },
      ],
    });

    const roadmap = await new RoadmapPlannerAgent(mock).generate(
      's1',
      downstreamCtx(TASK_BOARD_IDEA, pipeline),
    );
    expect(roadmapText(roadmap)).toContain('elasticsearch');
  });

  it('keeps heavier tooling when a requirement genuinely demands assurance', async () => {
    // The escape hatch in the prompt and the escape hatch in the code are the
    // same test, so the two can never disagree about when heavier tooling is
    // warranted.
    const base = await smallPipeline();
    const pipeline: Pipeline = {
      ...base,
      requirements: {
        ...base.requirements,
        nonFunctional: [
          ...base.requirements.nonFunctional,
          {
            id: 'NFR-3',
            category: 'availability',
            description: 'The contract commits to a 99.9% uptime target with monthly reporting.',
          },
        ],
      },
    };
    const mock = new MockLlmProvider();
    mock.enqueueJson({ summary: 'plan', phases: [reportedPhase] });

    const roadmap = await new RoadmapPlannerAgent(mock).generate(
      's1',
      downstreamCtx(TASK_BOARD_IDEA, pipeline),
    );
    expect(roadmapText(roadmap)).toContain('prometheus');
  });
});

// ── one tier, four prompts ──────────────────────────────────────────────────

describe('every downstream stage is told the same tier', () => {
  it('sends one identical verdict to roadmap, QA, threat model and review', async () => {
    const pipeline = await buildPipeline(
      's1',
      TASK_BOARD_IDEA,
      taskBoardRequirements(),
      taskBoardSlots(),
    );
    const ctx = downstreamCtx(TASK_BOARD_IDEA, pipeline);

    const sent: string[] = [];
    for (const run of [
      (llm: LlmProvider) => new RoadmapPlannerAgent(llm).generate('s1', ctx),
      (llm: LlmProvider) => new QaPlannerAgent(llm).generate('s1', ctx),
      (llm: LlmProvider) => new ThreatModelerAgent(llm).generate('s1', ctx),
      (llm: LlmProvider) => new ReviewerAgent(llm).generate('s1', ctx),
    ]) {
      const { llm, prompts } = recordingLlm();
      await run(llm);
      sent.push(prompts());
    }

    for (const prompt of sent) {
      expect(prompt).toContain('SCALE TIER: SMALL');
      expect(prompt).toContain('OPERATIONS BUDGET (Small/MVP tier)');
      // The escape hatch travels with the prohibition, or the model reads the
      // rule as absolute and drops assurance work a contract requires.
      expect(prompt).toContain('The ONLY exception');
    }
  });

  it('sends the large budget when the project is large', async () => {
    const pipeline = await buildPipeline(
      's2',
      CLINIC_IDEA,
      clinicRequirements(),
      clinicSlots(),
    );
    const { llm, prompts } = recordingLlm();
    await new RoadmapPlannerAgent(llm).generate(
      's2',
      downstreamCtx(CLINIC_IDEA, pipeline),
    );

    const sent = prompts();
    expect(sent).toContain('SCALE TIER: LARGE');
    expect(sent).toContain('Large/Enterprise tier');
    expect(sent).not.toContain('Do NOT introduce a dedicated observability stack');
  });

  it('sends no tier block at all for a design generated before tiers existed', async () => {
    // An absent tier means the previous behaviour — the same rule as an
    // unstamped sourceStamp never reading as stale. Guessing one here would size
    // a plan from an assessment nobody made.
    const pipeline = await buildPipeline(
      's1',
      TASK_BOARD_IDEA,
      taskBoardRequirements(),
      taskBoardSlots(),
    );
    const legacy: Pipeline = {
      ...pipeline,
      systemDesign: { ...pipeline.systemDesign, scaleTier: undefined },
    };
    const { llm, prompts } = recordingLlm();
    await new RoadmapPlannerAgent(llm).generate(
      's1',
      downstreamCtx(TASK_BOARD_IDEA, legacy),
    );

    expect(prompts()).not.toContain('SCALE TIER');
  });
});
