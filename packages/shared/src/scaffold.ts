/**
 * Deterministic **code scaffolding** — turns the confirmed design artifacts into
 * a runnable NestJS + Prisma backend starter. Pure and runtime-free (mirrors the
 * OpenAPI / structure / cost-estimate builders): no LLM, stable across runs, and
 * fully unit-testable offline.
 *
 * Mapping:
 *   - Database Design entities/relations → `prisma/schema.prisma` models.
 *   - API Design modules/endpoints       → NestJS modules, controllers, services,
 *                                           and class-validator DTOs.
 *   - System Design / idea               → root project files + README.
 *
 * Correctness over richness: the output always compiles and `prisma validate`s.
 * Foreign keys are emitted as scalar fields (documented via a comment) rather
 * than Prisma relations, so the schema is guaranteed valid regardless of how the
 * design names things; service methods are typed stubs that throw "Not
 * implemented", leaving the business logic to the developer.
 */

import type { SystemDesign } from './system-design';
import type { DatabaseDesign, Entity, EntityColumn } from './database-design';
import type { ApiDesign, ApiModule } from './api-design';
import {
  assignHandlers,
  camel,
  controllerBase,
  dedupe,
  fieldKind,
  httpMethod,
  kebab,
  mapName,
  oneLine,
  pascal,
  pascalMethod,
  prismaProvider,
  safePath,
  uniquifyNames,
  type Handler,
} from './scaffold.util';

/** A single generated file: a repo-relative path and its full text contents. */
export interface ScaffoldFile {
  path: string;
  content: string;
}

export interface ScaffoldInput {
  idea: string;
  systemDesign: SystemDesign;
  databaseDesign: DatabaseDesign;
  apiDesign: ApiDesign;
}

/**
 * What to generate: the NestJS backend, the Next.js frontend, or both as one
 * npm-workspaces monorepo (`apps/api` + `apps/web`).
 */
export type ScaffoldTarget = 'backend' | 'frontend' | 'fullstack';

export const SCAFFOLD_TARGETS: readonly ScaffoldTarget[] = [
  'backend',
  'frontend',
  'fullstack',
] as const;

/** The default when a caller doesn't say: the whole runnable app. */
export const DEFAULT_SCAFFOLD_TARGET: ScaffoldTarget = 'fullstack';

/** Manifest returned by the scaffold API (file list + count). */
export interface ScaffoldManifest {
  sessionId: string;
  generatedAt: string;
  target: ScaffoldTarget;
  /** Provider the deployment artifacts target (the cost recommendation by default). */
  provider: string;
  fileCount: number;
  files: ScaffoldFile[];
}

/** The port the generated frontend dev-serves on (the backend takes 3000). */
export const FRONTEND_DEV_PORT = 3001;

/** A user's GitHub connection state (no token material). */
