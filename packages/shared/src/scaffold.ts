function renderReadme(input: ScaffoldInput): string {
  const { idea, systemDesign, databaseDesign, apiDesign } = input;
  const entityList = databaseDesign.entities.map((e) => `- \`${e.name}\``).join('\n');
  const moduleList = apiDesign.modules
    .map((m) => `- **${m.name}** (${m.endpoints.length} endpoints)`)
    .join('\n');

  return [
    '# Generated Backend',
    '',
    '> Scaffolded by **Archivato AI Builder** from your system design. This is a',
    "> starting point — service methods are stubs that throw \"Not implemented\".",
    '',
    '## The idea',
    '',
    idea,
    '',
    `**Architecture:** ${systemDesign.architecture}`,
    '',
    '## Getting started',
    '',
    '```bash',
    'npm install',
    'cp .env.example .env      # set DATABASE_URL',
    'npm run prisma:migrate    # create the schema',
    'npm run start:dev         # http://localhost:3000/api',
    '```',
    '',
    '## Data model',
    '',
    entityList || '_No entities._',
    '',
    '## API modules',
    '',
    moduleList || '_No modules._',
    '',
    '## Next steps',
    '',
    '1. Review `prisma/schema.prisma` (foreign keys are scalar fields + comments;',
    '   convert them to Prisma relations where you want referential integrity).',
    '2. Implement each service method (they currently throw "Not implemented").',
    '3. Add authentication, validation, and tests.',
    '',
  ].join('\n');
}

function exampleDbUrl(databaseType: string): string {
  switch (prismaProvider(databaseType)) {
    case 'mysql':
      return 'mysql://user:password@localhost:3306/app';
    case 'sqlite':
      return 'file:./dev.db';
    case 'sqlserver':
      return 'sqlserver://localhost:1433;database=app;user=sa;password=Password1;';
    case 'mongodb':
      return 'mongodb://localhost:27017/app';
    default:
      return 'postgresql://user:password@localhost:5432/app?schema=public';
  }
}

// ── Path / casing helpers ────────────────────────────────────────────────────

/** Strip the leading `/api` and surrounding slashes from a designed path. */
function stripApi(p: string): string {
  return (p || '').replace(/^\/?api/i, '').replace(/^\/+|\/+$/g, '');
}

/** The controller base path (no leading slash), e.g. `/api/users` → `users`. */
function controllerBase(basePath: string, slug: string): string {
  const base = stripApi(basePath);
  return base || slug;
}

/**
 * An endpoint's path relative to its module base — the arg to `@Get(...)`.
 * `/api/users/:id` (base `/api/users`) → `:id`; `/api/users` → ``.
 */
function relativePath(endpointPath: string): string {
  const segments = stripApi(endpointPath).split('/').filter(Boolean);
  // Drop the first segment (the resource, already the controller base) and keep
  // the remainder (ids / sub-resources). This keeps nested paths intact.
  return segments.slice(1).join('/');
}

function words(s: string): string[] {
  return (s || '')
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/[^a-zA-Z0-9]+/g, ' ')
    .trim()
    .split(/\s+/)
    .filter(Boolean);
}

function pascal(s: string): string {
  const w = words(s);
  if (w.length === 0) return 'Resource';
  return w.map((x) => x[0].toUpperCase() + x.slice(1).toLowerCase()).join('');
}

function camel(s: string): string {
  const p = pascal(s);
  return p ? p[0].toLowerCase() + p.slice(1) : p;
}

function kebab(s: string): string {
  const w = words(s);
  return w.length ? w.map((x) => x.toLowerCase()).join('-') : 'resource';
}

function kebabFromClass(cls: string): string {
  return kebab(cls);
}

function pascalMethod(method: string): string {
  return method.charAt(0).toUpperCase() + method.slice(1).toLowerCase();
}

function dedupe(arr: string[]): string[] {
  return [...new Set(arr)];
}
